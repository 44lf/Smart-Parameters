# 文档分片不同策略适用哪些场景，每一种至少举一个例子进行说明。
# .1固定长度切分，文档结构弱（纯文本、聊天记录、日志）你只追求“快速稳定跑通”，不想引入复杂解析召回优先（宁可多切几块）
# 例如：客服聊天记录：每800字一块，每重叠100字，避免问答跨快导致信息断裂。

# 2.分割符切分，文档有明确分隔符：换行、空行、标题标记、段落符号（Markdown/纯文本），希望尽量不切断自然段落
# 例如，知识库，按##、###标题切，再按句号，空行切

# 3.递归分割切分，文档结构存在，但不总是规整，需要“尽量保持语义完整，同时控制长度”
# 例如：产品 PRD：先按章节标题切，章节太长再按段落切，仍太长再按句号切，保证 chunk 可控且不破坏结构。

# 4.句子/语义边界切分，对语义完整性要求高（问答、总结、合规条款）不希望“半句话/半段话”影响 embedding 与检索
# 例如：合同条款：按句号/分号切句，再按 10–15 句合并成块；保证引用时更连贯

# 5.token计数，你调用的 embedding/LLM 有明确 token 上限，且文本中中英混杂、字符长度不稳定，你想把 chunk 精确控制在例如 512/1024 tokens
# 例如：英文技术文档（含代码）：按 token 控制每块 700 tokens，避免字符法导致 token 溢出、API 报错。

# 6.结构化文档切分，英文技术文档（含代码）：按 token 控制每块 700 tokens，避免字符法导致 token 溢出、API 报错。
# 例如：PDF 说明书：按“页 → 标题块 → 段落”切，并在 metadata 存 page=12, section='3.2 安装'，检索结果可直接定位页码。

# 7.代码，配置文件专用切分，代码、SQL、YAML、日志配置：普通按句号/段落会破坏语法结构。希望 chunk 能对应函数/类/配置块
# 例如：Python 项目：按 def/class 作为边界切分；一个函数过长再按空行/注释块拆；metadata 存 symbol=ClassA.method_x 便于定位。


# 8.FAQ / 问答对切分（Pairing chunking），数据天然是“问题-答案”结构，检索时希望命中“完整问答对”，而不是答案碎片
# 例如：内部支持中心/客服FAQ：每个条目（问题+答案+适用范围/标签）作为一个 chunk；检索命中后直接返回该条目。

# 9.表格/列表专用切分（Table/List-aware），文档里大量表格、清单、参数矩阵；普通切分会打断行列关系，导致检索结果不可用
# 例如：API 参数表：每张表作为一个 chunk；表太大则按 20 行一块，并在每块重复表头（列名），避免命中后缺上下文。

# 10.多粒度切分（Multi-granularity），既要“段落级精准召回”，又要“章节级覆盖/概览”；同一文档生成多套 chunks（小/中/大）
# 例如：技术手册：同时写入两套 chunk
# - 小块：300~500 tokens（精准定位）
# - 大块：1200~1500 tokens（上下文覆盖）
# 检索时先召回小块，不够再补大块，或用 rerank 统一排序。